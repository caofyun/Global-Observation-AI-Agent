import sys
import os
import json


# ==========================================
# 添加项目根目录
# ==========================================

sys.path.append(
    os.path.dirname(
        os.path.dirname(__file__)
    )
)


from src.agents.news_agent import NewsAgent
from src.core.project_manager import ProjectManager


# ==========================================
# 创建项目管理器
# ==========================================

project_manager = ProjectManager()


# ==========================================
# 创建NewsAgent
# ==========================================

news_agent = NewsAgent()


# ==========================================
# 输入新闻选题
# ==========================================

topic = input(
    "请输入新闻选题："
).strip()


# ==========================================
# 检查输入
# ==========================================

if not topic:

    print(
        "新闻选题不能为空"
    )

    sys.exit()


# ==========================================
# 创建视频项目
# ==========================================

print()
print("==============================")
print("正在创建测试视频项目")
print("==============================")


project_path = project_manager.create_project(
    topic
)


# ==========================================
# 调用NewsAgent V2.0
# ==========================================

result = news_agent.run({

    "topic": topic,

    "project_path": project_path

})


# ==========================================
# 输出结果
# ==========================================

print()
print("==============================")
print("NewsAgent V2.0 测试结果")
print("==============================")


print(
    json.dumps(
        result,
        ensure_ascii=False,
        indent=4
    )
)


# ==========================================
# 输出Agent状态
# ==========================================

print()
print("==============================")
print("Agent状态")
print("==============================")


print(
    news_agent.get_status()
)