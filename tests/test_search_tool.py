import sys
import os
import json


# ==========================================
# 添加项目根目录
# ==========================================

sys.path.append(
    os.path.dirname(
        os.path.dirname(__file__)
    )
)


from src.utils.search_tool import SearchTool


# ==========================================
# 创建SearchTool
# ==========================================

search_tool = SearchTool()


# ==========================================
# 输入搜索关键词
# ==========================================

keyword = input(
    "请输入新闻搜索关键词："
).strip()


# ==========================================
# 执行搜索
# ==========================================

results = search_tool.search(
    keyword,
    max_results=10
)


# ==========================================
# 输出搜索结果
# ==========================================

print()
print("==============================")
print("搜索结果")
print("==============================")


print(
    json.dumps(
        results,
        ensure_ascii=False,
        indent=4
    )
)


# ==========================================
# 输出结果数量
# ==========================================

print()
print("==============================")
print(
    f"共返回 {len(results)} 条结果"
)
print("==============================")